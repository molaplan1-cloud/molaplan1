#!/bin/sh
# Regenerates src/ca_roots.h from the system CA store: the roots behind relay.molaplan.com (Google
# Trust Services, cross-signed by GlobalSign) and ntfy.sh / most other sites (ISRG / Let's Encrypt).
set -e
out="$(dirname "$0")/../src/ca_roots.h"
{
  echo "// Generated by tools/gen_ca_roots.sh – trusted roots for the relay and ntfy (TLS verification)."
  echo "#pragma once"
  echo "static const char kCaRoots[] ="
  for c in GTS_Root_R1 GTS_Root_R4 GlobalSign_Root_CA ISRG_Root_X1 ISRG_Root_X2; do
    sed 's/^/  "/; s/$/\\n"/' "/etc/ssl/certs/$c.pem"
  done
  echo "  ;"
} > "$out"

#!/usr/bin/env python3
"""Regenerates test/test_core/vectors_py.h: Ed25519/OTA vectors (fixed TEST key, not the release key)
and partition tables produced by ESP-IDF's own gen_esp32part.py."""
import os, subprocess, sys, tempfile
sys.path.insert(0, os.path.dirname(__file__))
from sign_ota import manifest, b64url
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization

GEN = sys.argv[1]  # path to gen_esp32part.py
seed = bytes(range(32))
pub = Ed25519PrivateKey.from_private_bytes(seed).public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
image = bytes((i * 7) & 0xFF for i in range(5000))
m = manifest(image, "0.8.1", "https://example.invalid/fw.bin", seed)

TASMOTA = """nvs,data,nvs,0x9000,0x5000
otadata,data,ota,0xe000,0x2000
safeboot,app,factory,0x10000,0xD0000
app0,app,ota_0,0xE0000,0x2F0000
spiffs,data,spiffs,0x3D0000,0x430000
"""
EXPECT = """nvs,data,nvs,0x9000,0x5000
otadata,data,ota,0xe000,0x2000
safeboot,app,factory,0x10000,0xD0000
app0,app,ota_0,0xE0000,0x2F0000
app1,app,ota_1,0x3D0000,0x2F0000
"""


def table(csv):
    with tempfile.TemporaryDirectory() as d:
        open(f"{d}/p.csv", "w").write(csv)
        subprocess.check_call([sys.executable, GEN, "-q", f"{d}/p.csv", f"{d}/p.bin"])
        return open(f"{d}/p.bin", "rb").read()


def carr(name, b):
    return f"static const uint8_t {name}[{len(b)}] = {{" + ",".join(str(x) for x in b) + "};"


out = ["// Generated by tools/gen_test_vectors.py – do not edit.", "#pragma once", "#include <stdint.h>",
       f'#define T_ED_PUB "{b64url(pub)}"', f'#define T_IMAGE_SHA "{m["sha256"]}"', f'#define T_SIG "{m["sig"]}"',
       f"#define T_SIZE {m['size']}", f"#define T_CODE {m['code']}", f'#define T_VERSION "{m["version"]}"',
       carr("T_TASMOTA_TABLE", table(TASMOTA)), carr("T_EXPECT_TABLE", table(EXPECT))]
print("\n".join(out))

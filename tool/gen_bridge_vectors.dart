// Generates interop vectors for the ESP32 bridge host tests:
//   dart run tool/gen_bridge_vectors.dart > firmware/molaplan-bridge/test/test_core/vectors.h
// Uses the app's own e2e.dart so the firmware is tested against exactly what the phone does.
import 'dart:convert';
import 'dart:io';

import 'package:cryptography/cryptography.dart';
import 'package:molaplan/remote/e2e.dart';

Future<void> main() async {
  final phone = await Identity.fromSeed(List.generate(32, (i) => i + 1));
  final bridge = await Identity.fromSeed(List.generate(32, (i) => 200 - i));
  const home = '0123456789abcdef0123456789abcdef';
  const dev = 'phone-test-1';
  final k1 = await sessionKey(phone, bridge.publicKey, home, dev);
  final k2 = await sessionKey(bridge, phone.publicKey, home, dev);
  final kb = await k1.extractBytes();
  if (hex(kb) != hex(await k2.extractBytes())) throw 'asymmetric';
  final msg = {
    'n': 'n0001',
    'ts': 1764000000000,
    'b': [
      {'id': '1', 'op': 'ping'},
    ],
  };
  final nonce = List.generate(12, (i) => 0xA0 + i);
  final box = await AesGcm.with256bits().encrypt(
    utf8.encode(jsonEncode(msg)),
    secretKey: k1,
    nonce: nonce,
    aad: utf8.encode('$home|$dev|c2b'),
  );
  final fixed = b64(box.concatenation());
  final random = await seal(k1, msg, home: home, dev: dev, dir: 'c2b');
  final mac = await pairMac('483921', 'p1|$home|$dev|${b64(phone.publicKey)}');
  final out = StringBuffer()
    ..writeln('// Generated by tool/gen_bridge_vectors.dart from lib/remote/e2e.dart – do not edit.')
    ..writeln('#pragma once')
    ..writeln('#define V_HOME "$home"')
    ..writeln('#define V_DEV "$dev"')
    ..writeln('#define V_PHONE_SEED "${hex(phone.seed)}"')
    ..writeln('#define V_PHONE_PUB "${b64(phone.publicKey)}"')
    ..writeln('#define V_BRIDGE_SEED "${hex(bridge.seed)}"')
    ..writeln('#define V_BRIDGE_PUB "${b64(bridge.publicKey)}"')
    ..writeln('#define V_SESSION_KEY "${hex(kb)}"')
    ..writeln('#define V_MSG ${jsonEncode(jsonEncode(msg))}')
    ..writeln('#define V_NONCE "${hex(nonce)}"')
    ..writeln('#define V_FRAME_FIXED "$fixed"')
    ..writeln('#define V_FRAME_RANDOM "$random"')
    ..writeln('#define V_PAIR_MAC "$mac"')
    ..writeln('#define V_SHA_PAIR "${await sha256Hex('molaplan-pair|483921')}"');
  stdout.writeln(out.toString().trimRight());
}
